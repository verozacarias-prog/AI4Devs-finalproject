def test_a_pending_expires_unless_it_comes_from_a_recurring_rule(rows: Rows, home: Home) -> None:
    # Case 124.
    manual = rows.batch(home.user)
    automatic = rows.batch(home.user, source=AUTOMATIC)
    rule = rows.rule(home)
    rows.pending(home.user, manual)
    rows.pending(home.user, automatic, **_of_rule(rule))

    with rows.rejected_by("ck_pending_transaction_expires_iff_no_rule"):
        rows.pending(home.user, manual, position=2, expires_at=None)
    with rows.rejected_by("ck_pending_transaction_expires_iff_no_rule"):
        rows.pending(
            home.user,
            automatic,
            position=2,
            **_of_rule(
                rule,
                occurrence_date=MOVEMENT_DATE + timedelta(days=31),
                expires_at=OPENED_AT + timedelta(days=90),
            ),
        )


RESULTS: dict[str, Callable[[Rows, Home], dict[str, object]]] = {
    "transaction": _promoted_to_transaction,
    "transfer": _promoted_to_transfer,
    "recurring_rule": _promoted_to_rule,
}


@pytest.mark.parametrize("result", list(RESULTS))
def test_two_pendings_do_not_become_the_same_row(rows: Rows, home: Home, result: str) -> None:
    # Case 135. Pendings that were not promoted point to nothing and do not collide.
    batch = rows.batch(home.user)
    promoted = RESULTS[result](rows, home)
    rows.pending(home.user, batch, position=1)
    rows.pending(home.user, batch, position=2)
    rows.pending(home.user, batch, position=3, **promoted)

    with rows.rejected_by(f"uq_pending_transaction_resulting_{result}"):
        rows.pending(home.user, batch, position=4, **promoted)


def test_a_user_has_one_batch_in_conversation(rows: Rows, home: Home) -> None:
    # Case 96. Batches that are not in conversation do not count, nor the one of another user.
    rows.batch(home.user)
    rows.batch(home.user)
    rows.batch(home.user, awaiting_reply=True)
    rows.batch(rows.user(), awaiting_reply=True)

    with rows.rejected_by("uq_pending_batch_user_awaiting"):
        rows.batch(home.user, awaiting_reply=True)


def test_a_closed_batch_is_not_in_conversation(rows: Rows, home: Home) -> None:
    # Case 123.
    rows.batch(home.user, status="closed")

    with rows.rejected_by("ck_pending_batch_closed_not_awaiting"):
        rows.batch(home.user, status="closed", awaiting_reply=True)


