"""PENDING_TRANSACTION, PENDING_BATCH and the two message tables: cases 85 to 101, and block D."""

from __future__ import annotations

import uuid
from collections.abc import Callable
from datetime import timedelta

import pytest

from tests.integration.schema.names import (
    AUTOMATIC,
    META,
    OUTSIDE_THE_SET,
    PROMOTED,
    TWILIO,
    WEB,
)
from tests.integration.schema.rows import MOVEMENT_DATE, OPENED_AT, Home, Rows

pytestmark = pytest.mark.integration


@pytest.fixture
def home(rows: Rows) -> Home:
    return rows.home()


def _of_rule(rule: uuid.UUID, **overrides: object) -> dict[str, object]:
    """A pending generated by a recurring rule: it never expires."""
    return {
        "recurring_rule_id": rule,
        "occurrence_date": MOVEMENT_DATE,
        "source": AUTOMATIC,
        "expires_at": None,
        **overrides,
    }


def _promoted_to_transaction(rows: Rows, home: Home) -> dict[str, object]:
    return {"status": PROMOTED, "resulting_transaction_id": rows.transaction(home)}


def _promoted_to_transfer(rows: Rows, home: Home) -> dict[str, object]:
    transfer = rows.transfer(home.user, home.account, rows.account(home.user))
    return {"status": PROMOTED, "intent": "transfer", "resulting_transfer_id": transfer}


def _promoted_to_rule(rows: Rows, home: Home) -> dict[str, object]:
    return {
        "status": PROMOTED,
        "intent": "recurring_rule",
        "resulting_recurring_rule_id": rows.rule(home),
    }


@pytest.mark.parametrize("column", ["status", "intent", "source"], ids=["85", "86", "133"])
def test_the_status_the_intent_and_the_source_of_a_pending_come_from_a_closed_set(
    rows: Rows, home: Home, column: str
) -> None:
    # Cases 85, 86 and 133.
    batch = rows.batch(home.user)
    rows.pending(home.user, batch, intent="change", status="rejected")

    with rows.rejected_by(f"ck_pending_transaction_{column}"):
        rows.pending(home.user, batch, position=2, **{column: OUTSIDE_THE_SET})


def test_a_promoted_pending_points_to_what_it_became(rows: Rows, home: Home) -> None:
    # Case 87. A change is the exception: it creates no row, so it points to none.
    batch = rows.batch(home.user)
    rows.pending(home.user, batch, **_promoted_to_transaction(rows, home))
    rows.pending(home.user, batch, position=2, intent="change", status=PROMOTED)

    with rows.rejected_by("ck_pending_transaction_result"):
        rows.pending(home.user, batch, position=3, status=PROMOTED)


def test_a_pending_that_was_not_promoted_points_to_nothing(rows: Rows, home: Home) -> None:
    # Case 88.
    batch = rows.batch(home.user)
    rows.pending(home.user, batch)
    result = rows.transaction(home)

    with rows.rejected_by("ck_pending_transaction_result"):
        rows.pending(home.user, batch, position=2, resulting_transaction_id=result)


def test_a_promoted_pending_points_to_one_result_only(rows: Rows, home: Home) -> None:
    # Case 89.
    batch = rows.batch(home.user)
    promoted = _promoted_to_transaction(rows, home)
    rows.pending(home.user, batch, **promoted)
    transfer = rows.transfer(home.user, home.account, rows.account(home.user))

    with rows.rejected_by("ck_pending_transaction_result"):
        rows.pending(
            home.user,
            batch,
            position=2,
            status=PROMOTED,
            resulting_transaction_id=rows.transaction(home),
            resulting_transfer_id=transfer,
        )


def test_a_pending_of_a_recurring_rule_becomes_a_movement(rows: Rows, home: Home) -> None:
    # Case 90.
    batch = rows.batch(home.user, source=AUTOMATIC)
    rule = rows.rule(home)
