def test_an_inbound_message_of_the_provider_is_stored_once(rows: Rows) -> None:
    # Case 97. The same identifier from another provider is another message.
    rows.inbound(provider=META, provider_message_id="wamid.1")
    rows.inbound(provider=TWILIO, provider_message_id="wamid.1")

    with rows.rejected_by("uq_inbound_message_provider_message"):
        rows.inbound(provider=META, provider_message_id="wamid.1")


def test_an_outbound_message_of_the_provider_is_stored_once(rows: Rows, home: Home) -> None:
    # Case 98. Messages the provider has not accepted yet have no identifier and do not collide.
    rows.outbound(home.user, provider=META, status="pending")
    rows.outbound(home.user, provider=META, status="pending")
    rows.outbound(home.user, provider=META, provider_message_id="wamid.1")

    with rows.rejected_by("uq_outbound_message_provider_message"):
        rows.outbound(home.user, provider=META, provider_message_id="wamid.1")


